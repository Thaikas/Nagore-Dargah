            <p class="dropcap">Hazrat Syed Shahul Hameed Qadir Wali (Q.S.) — known to the people of the south as <strong>Nagore Andavar</strong>, <strong>Meeran Sahib</strong> and <strong>Ganj-e-Sawai</strong> — was born in <strong>1490 CE</strong> at Manikpur in the Pratapgarh district of present-day Uttar Pradesh. He was the son of Hazrat Syed Hassan Kuthos Baba Qadiri and Bibi Fathima, and a thirteenth-generation descendant of the great saint <strong>Hazrat Muhiyudin Abdul Qadir al-Jilani (R.A.)</strong>, founder of the Qadiriyya order.</p>

            <p>From a young age the saint devoted himself to the study of the Qur'an and the spiritual sciences. After years of learning and travel across the holy lands and the Indian subcontinent, he journeyed southward, spreading a message of divine love, compassion and service to all of creation. After Hazrat Nathar Wali Shah, no Sufi exerted a greater influence upon Tamil Nadu than Shahul Hameed.</p>

            <h2>The Miracle at Thanjavur</h2>
            <p>Tradition holds that <strong>Achutappa Nayak</strong>, the sixteenth-century Hindu king of Thanjavur, was afflicted by a grave ailment that no physician could heal. Hearing of the saint's spiritual station, the king sought his blessing — and was cured. In gratitude, Achutappa Nayak gifted <strong>around 200 acres (81 hectares)</strong> of land to the saint and his companions. Upon a part of this land, the Dargah was later raised.</p>

            <p>This founding story is the heart of Nagore's identity: a Muslim saint healing a Hindu king, a shrine built upon a king's gratitude, and a sanctuary that has welcomed devotees of every faith ever since. To this day, the Dargah is maintained and beloved with major contributions from Hindus as well as Muslims.</p>

            <h2>The Shrine and Its Five Minarets</h2>
            <p>The saint passed from this world in <strong>1579 CE</strong> and was laid to rest at Nagore, on the Coromandel coast. The Dargah grew over the centuries through the devotion of countless pilgrims. Its most striking features are the <strong>five minarets (manaras)</strong> that rise around the central dome:</p>
            <ul>
                <li><strong>Periya Manara</strong> — 131 ft, the tallest, built by the Maratha king <strong>Pratap Singh (1739–1763 CE)</strong> in thanksgiving for the birth of a son.</li>
                <li><strong>Thalaimattu Minara</strong> — 93.5 ft</li>
                <li><strong>Muthubaq Minara</strong> — 93.25 ft</li>
                <li><strong>Ottu Minara</strong> — 80 ft</li>
                <li><strong>Sahib Minara</strong> — 77 ft</li>
            </ul>
            <p>Around the shrine lie sacred tanks (ponds) where pilgrims gather, and the great flagstaff from which the Uroos flag is hoisted each year.</p>

            <h2>A Legacy of Harmony</h2>
